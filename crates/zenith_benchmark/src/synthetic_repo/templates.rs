//! The fixed text of a synthetic repository: root manifests and configs, and
//! the templates that source files are filled in from.
//!
//! The templates of importable modules (components, hooks, API clients,
//! utilities, handlers, jobs and stores) share these placeholders:
//!
//! - `__S__`: the module's exported symbol, e.g. `useBillingQuery`;
//! - `__T__`: the same, starting with a capital letter;
//! - `__K__`: a kebab-case key from its feature and file name, e.g.
//!   `billing-use-query`;
//! - `__N__`: a small number, so that modules differ.
//!
//! The other templates describe their own placeholders.

